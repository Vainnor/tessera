import { COLOR_ROLES, type FontFamily, type Theme } from "./types.ts";

/** System font stacks. Tessera ships and fetches no font files. */
export const FONT_STACKS: Record<FontFamily, string> = {
  sans: 'system-ui, -apple-system, "Segoe UI", Roboto, "Noto Sans", "Helvetica Neue", Arial, sans-serif',
  serif: 'ui-serif, "Iowan Old Style", "Palatino Linotype", Palatino, Georgia, "Noto Serif", serif',
  mono: 'ui-monospace, "SF Mono", SFMono-Regular, Menlo, Consolas, "Cascadia Mono", "Liberation Mono", "Noto Sans Mono", monospace',
};

const DENSITY_FACTOR = { compact: 0.75, comfortable: 1, spacious: 1.25 } as const;

const kebab = (name: string): string => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** The CSS custom properties one theme sets, by name. Values are already validated. */
export function themeVariables(theme: Theme): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const role of COLOR_ROLES) vars[`--t-color-${kebab(role)}`] = theme.colors[role];
  const shadowAlpha = theme.mode === "dark" ? 0.4 : 0.12;
  Object.assign(vars, {
    "--t-font-body": FONT_STACKS[theme.typography.body],
    "--t-font-heading": FONT_STACKS[theme.typography.heading],
    "--t-font-code": FONT_STACKS.mono,
    "--t-type-scale": String(theme.typography.scale),
    "--t-heading-case": theme.typography.headingCase,
    "--t-radius-base": `${theme.radius}px`,
    "--t-density": String(DENSITY_FACTOR[theme.density]),
    "--t-shadow-1": theme.elevation === "raised" ? `0 1px 2px rgb(0 0 0 / ${shadowAlpha})` : "none",
    "--t-shadow-2":
      theme.elevation === "raised"
        ? `0 4px 12px rgb(0 0 0 / ${shadowAlpha}), 0 1px 3px rgb(0 0 0 / ${shadowAlpha})`
        : "none",
    "--t-motion": theme.motion ? "1" : "0",
  });
  return vars;
}

/** Tokens every theme shares. They scale with the theme's density, type scale and radius. */
const SCALE_TOKENS: Record<string, string> = {
  ...Object.fromEntries(
    [4, 8, 12, 16, 24, 32, 48, 64].map((px, i) => [
      `--t-space-${i + 1}`,
      `calc(${px}px * var(--t-density))`,
    ]),
  ),
  ...Object.fromEntries(
    (
      [
        ["xs", 0.75],
        ["sm", 0.875],
        ["base", 1],
        ["md", 1.125],
        ["lg", 1.25],
        ["xl", 1.5],
        ["2xl", 2],
      ] as const
    ).map(([name, rem]) => [`--t-text-${name}`, `calc(${rem}rem * var(--t-type-scale))`]),
  ),
  "--t-leading-tight": "1.25",
  "--t-leading-normal": "1.5",
  "--t-leading-relaxed": "1.7",
  "--t-weight-regular": "400",
  "--t-weight-medium": "500",
  "--t-weight-bold": "700",
  "--t-radius-sm": "calc(var(--t-radius-base) * 0.5)",
  "--t-radius-md": "var(--t-radius-base)",
  "--t-radius-lg": "calc(var(--t-radius-base) * 2)",
  "--t-radius-full": "9999px",
  "--t-focus-width": "2px",
  "--t-focus-offset": "2px",
  "--t-motion-pref": "1",
  "--t-duration-fast": "calc(120ms * var(--t-motion) * var(--t-motion-pref))",
  "--t-duration-base": "calc(200ms * var(--t-motion) * var(--t-motion-pref))",
  "--t-duration-slow": "calc(320ms * var(--t-motion) * var(--t-motion-pref))",
  "--t-ease-standard": "cubic-bezier(0.2, 0, 0, 1)",
};

const block = (selector: string, vars: Record<string, string>, extra = ""): string =>
  `${selector} {\n${Object.entries(vars)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n")}${extra}\n}\n`;

const themeBlock = (selector: string, theme: Theme): string =>
  block(selector, themeVariables(theme), `\n  color-scheme: ${theme.mode};`);

const indent = (css: string): string =>
  css
    .split("\n")
    .map((line) => (line ? `  ${line}` : line))
    .join("\n");

/**
 * The stylesheet both apps load. With no `data-theme` on the root, the OS color scheme picks
 * between the two defaults; `data-theme="<id>"` selects a preset explicitly.
 */
export function buildStylesheet(
  presets: readonly Theme[],
  defaults: { dark: string; light: string },
): string {
  const byId = (id: string): Theme => {
    const theme = presets.find((t) => t.id === id);
    if (!theme) throw new Error(`default theme "${id}" is not a preset`);
    return theme;
  };
  return [
    "/* Generated by packages/theme/scripts/build.ts from presets/*.json. Do not edit. */\n",
    block(":root,\n[data-theme]", SCALE_TOKENS),
    themeBlock(":root", byId(defaults.dark)),
    `@media (prefers-color-scheme: light) {\n${indent(themeBlock(":root:not([data-theme])", byId(defaults.light)))}}\n`,
    ...presets.map((theme) => themeBlock(`[data-theme="${theme.id}"]`, theme)),
    `@media (prefers-reduced-motion: reduce) {\n${indent(block(":root,\n[data-theme]", { "--t-motion-pref": "0" }))}}\n`,
  ].join("\n");
}
